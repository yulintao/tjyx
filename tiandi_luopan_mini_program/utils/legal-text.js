function getDoc(key) {
  return DOCS[key] || null;
}

/** 拆成段落数组，便于 wxml 渲染 */
function paragraphs(key) {
  const doc = getDoc(key);
  if (!doc) return [];
  return doc.body.split(/\n+/).map((s) => s.trim()).filter(Boolean);
}

